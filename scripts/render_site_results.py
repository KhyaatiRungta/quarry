"""Write the results table in site/index.html from results/bench_results.json.

The site is static HTML with no JavaScript, so it cannot read the results file at
load time. Rather than typing numbers into the page by hand, this script injects
them between two markers. Every number in the Results section therefore comes from
a real run, and anything that has not been measured is printed as `pending`.

    python scripts/render_site_results.py
"""
from __future__ import annotations

import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results" / "bench_results.json"
PAGE = ROOT / "site" / "index.html"
BEGIN = "<!-- RESULTS:BEGIN generated by scripts/render_site_results.py from results/bench_results.json -->"
END = "<!-- RESULTS:END -->"
MBEGIN = "<!-- METRICS:BEGIN generated by scripts/render_site_results.py from results/bench_results.json -->"
MEND = "<!-- METRICS:END -->"

ROWS = [
    ("task success rate", "task_success_rate", "pct"),
    ("tasks graded", "tasks_graded", "int"),
    ("median steps", "median_steps", "num"),
    ("repair rate (runs with at least one repair)", "repair_rate", "pct"),
    ("repair success rate", "repair_success_rate", "pct"),
    ("grounded answer rate", "grounded_rate", "pct"),
    ("mean cost per task", "mean_cost_usd_per_task", "usd"),
    ("median latency", "median_latency_s", "sec"),
    ("p95 latency", "p95_latency_s", "sec"),
    ("sandbox violations", "sandbox_violations", "int"),
]

PENDING = '<span class="pending">pending</span>'


def fmt(value, kind: str) -> str:
    if value is None:
        return PENDING
    if kind == "pct":
        return f"{100 * float(value):.1f}%"
    if kind == "usd":
        return f"${float(value):.4f}"
    if kind == "sec":
        return f"{float(value):.2f}s"
    if kind == "int":
        return str(int(value))
    return f"{float(value):g}"


def render(payload: dict) -> str:
    arms = payload.get("arms", {})
    on, off = arms.get("on", {}), arms.get("off", {})
    mode = payload.get("mode")
    status = payload.get("status")
    full_suite = status == "complete"

    parts = [BEGIN]

    if not full_suite:
        parts.append(
            '<table><caption>Full 43-task suite, both arms, live model &mdash; not yet run. '
            'These rows are placeholders, not measurements.</caption>'
            '<thead><tr><th>metric</th><th class="n">self-correction ON</th>'
            '<th class="n">self-correction OFF</th></tr></thead><tbody>'
        )
        for label, _key, _kind in ROWS:
            parts.append(f'<tr><td>{html.escape(label)}</td>'
                         f'<td class="n">{PENDING}</td><td class="n">{PENDING}</td></tr>')
        parts.append("</tbody></table>")
        parts.append(
            '<p class="prose">Running the full suite costs real tokens and needs an OpenRouter '
            'key, so it has not been run here. <code>python -m quarry bench</code> fills this '
            'table in: the runner writes <code>results/bench_results.json</code> and '
            '<code>results/RESULTS.md</code>, and this page is regenerated from that file by '
            '<code>scripts/render_site_results.py</code>. Nothing on this page is typed in by '
            'hand.</p>')

    caption = {
        "offline_smoke": "Measured. Offline harness run: recorded model turns, real sandbox "
                         "execution, real grading, real timings. "
                         f"{on.get('tasks_attempted', 0)} of {payload.get('tasks_total')} tasks "
                         "have a recorded fixture; the rest are skipped, not failed.",
        "partial": f"Measured. Partial live run over {payload.get('tasks_run')} of "
                   f"{payload.get('tasks_total')} tasks.",
        "complete": f"Measured. Full live run over {payload.get('tasks_total')} tasks, "
                    f"model {payload.get('model')}.",
        "pending": "No run has been recorded yet.",
    }.get(status, "")

    parts.append(f'<table><caption>{html.escape(caption)}</caption>'
                 '<thead><tr><th>metric</th><th class="n">self-correction ON</th>'
                 '<th class="n">self-correction OFF</th></tr></thead><tbody>')
    for label, key, kind in ROWS:
        parts.append(
            f'<tr><td>{html.escape(label)}</td>'
            f'<td class="n">{fmt(on.get(key), kind)}</td>'
            f'<td class="n">{fmt(off.get(key), kind)}</td></tr>')
    parts.append("</tbody></table>")

    parts.append(
        f'<p class="prose dim mono" style="font-size:0.78rem">generated '
        f'{html.escape(str(payload.get("generated_at")))} &middot; mode '
        f'{html.escape(str(mode))} &middot; model '
        f'<code>{html.escape(str(payload.get("model")))}</code> &middot; status '
        f'{html.escape(str(status))} &middot; source '
        f'<code>results/bench_results.json</code></p>')
    parts.append(f'<p class="prose">{html.escape(str(payload.get("note", "")))}</p>')
    parts.append(END)
    return "\n  ".join(parts)


def render_metrics(payload: dict) -> str:
    """The headline strip. Every figure is read from the results file or printed as pending,
    and each label says which run produced it so a measured smoke number cannot be mistaken
    for the full suite."""
    arms = payload.get("arms", {})
    on, off = arms.get("on", {}), arms.get("off", {})
    full = payload.get("status") == "complete"
    scope = "full suite" if full else f"offline smoke, {on.get('tasks_attempted', 0)} tasks"

    cells = [
        (str(payload.get("tasks_total")), "tasks in the benchmark suite"),
        (fmt(on.get("task_success_rate"), "pct") if full else PENDING,
         "task success, self-correction on"
         + ("" if full else " &mdash; full suite not yet run")),
        (fmt(on.get("repair_success_rate"), "pct"),
         f"failed executions recovered ({scope})"),
        (fmt(on.get("sandbox_violations"), "int"),
         f"sandbox violations that reached execution ({scope})"),
    ]
    parts = [MBEGIN, '<div class="metrics">']
    for value, label in cells:
        cls = "metric-value pending" if PENDING in value else "metric-value"
        parts.append(f'<div class="metric"><div class="{cls}">{value}</div>'
                     f'<span class="metric-label">{label}</span></div>')
    parts.append("</div>")
    parts.append(MEND)
    return "\n  ".join(parts)


def _splice(page: str, begin: str, end: str, block: str) -> str:
    start = page.index(begin)
    stop = page.index(end) + len(end)
    return page[:start] + block + page[stop:]


def main() -> int:
    payload = json.loads(RESULTS.read_text())
    page = PAGE.read_text()
    page = _splice(page, BEGIN, END, render(payload))
    page = _splice(page, MBEGIN, MEND, render_metrics(payload))
    PAGE.write_text(page)
    print(f"injected {payload['status']} results ({payload['mode']}) into {PAGE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
